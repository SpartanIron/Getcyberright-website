import Anthropic from "@anthropic-ai/sdk";
import { db } from "./db";
import { trendingThreats } from "@shared/schema";
import { eq, and, lt, sql } from "drizzle-orm";

const anthropic = new Anthropic({
  apiKey: process.env.AI_INTEGRATIONS_ANTHROPIC_API_KEY,
  baseURL: process.env.AI_INTEGRATIONS_ANTHROPIC_BASE_URL,
});

const REGION_DEFINITIONS: Record<string, string> = {
  "US": "United States",
  "CA": "Canada",
  "GB": "United Kingdom",
  "EU": "Europe (EU member states)",
  "AU": "Australia",
  "NZ": "New Zealand",
  "AF_WEST": "West Africa (Ghana, Nigeria, Senegal, etc.)",
  "AF_EAST": "East Africa (Kenya, Tanzania, Uganda, etc.)",
  "AF_SOUTH": "Southern Africa (South Africa, Botswana, etc.)",
  "SA": "South America",
  "AS_SOUTH": "South Asia (India, Pakistan, Bangladesh, etc.)",
  "AS_SOUTHEAST": "Southeast Asia (Philippines, Indonesia, Malaysia, etc.)",
  "GLOBAL": "Global (affects all regions)",
};

const AUDIENCE_DEFINITIONS: Record<string, string> = {
  "seniors": "Older adults (60+) who may be less familiar with technology",
  "families": "Parents and caregivers protecting their households",
  "children": "Young people under 18 and their online safety",
  "general": "All internet users regardless of age or background",
};

interface GeneratedThreat {
  title: string;
  summary: string;
  source: string;
  category: string;
  severity: string;
  regions: string[];
  audience: string;
  linkUrl?: string;
}

export async function refreshTrendingThreats(): Promise<{ added: number; expired: number }> {
  const now = new Date();
  const expiredResult = await db
    .update(trendingThreats)
    .set({ isActive: false })
    .where(
      and(
        eq(trendingThreats.isActive, true),
        lt(trendingThreats.expiresAt, now)
      )
    )
    .returning();

  const expiredCount = expiredResult.length;

  const existingActive = await db
    .select({ title: trendingThreats.title })
    .from(trendingThreats)
    .where(eq(trendingThreats.isActive, true));

  const existingTitles = existingActive.map(t => t.title);

  let newThreats: GeneratedThreat[] = [];
  try {
    newThreats = await generateThreatsWithAI(existingTitles);
  } catch (error) {
    console.error("Failed to generate trending threats with AI:", error);
    return { added: 0, expired: expiredCount };
  }

  let addedCount = 0;
  for (const threat of newThreats) {
    try {
      const expiresAt = new Date();
      expiresAt.setDate(expiresAt.getDate() + 7);

      const sanitize = (s: string) => s.replace(/\u2014/g, ",").replace(/\u2013/g, ",");
      await db.insert(trendingThreats).values({
        title: sanitize(threat.title),
        summary: sanitize(threat.summary),
        source: threat.source,
        category: threat.category,
        severity: threat.severity,
        regions: threat.regions,
        audience: threat.audience,
        linkUrl: threat.linkUrl || null,
        isActive: true,
        isAutoGenerated: true,
        displayOrder: 0,
        expiresAt,
      });
      addedCount++;
    } catch (error) {
      console.error("Failed to insert threat:", threat.title, error);
    }
  }

  console.log(`Trending threats refresh: expired ${expiredCount}, added ${addedCount}`);
  return { added: addedCount, expired: expiredCount };
}

async function generateThreatsWithAI(existingTitles: string[]): Promise<GeneratedThreat[]> {
  const regionList = Object.entries(REGION_DEFINITIONS)
    .map(([code, name]) => `- ${code}: ${name}`)
    .join("\n");

  const audienceList = Object.entries(AUDIENCE_DEFINITIONS)
    .map(([code, desc]) => `- ${code}: ${desc}`)
    .join("\n");

  const existingList = existingTitles.length > 0
    ? `\nAlready displayed (do NOT duplicate these):\n${existingTitles.map(t => `- ${t}`).join("\n")}`
    : "";

  const prompt = `You are a cybersecurity analyst for GetCyberRight.com, a free family-focused cybersecurity education platform. Generate 3-5 current, real trending cybersecurity threats that are actively affecting people right now.

CRITICAL RULES:
- Every threat must be based on REAL, currently active cybersecurity issues
- Use proper punctuation throughout. Never use em dashes. Use commas, periods, and semicolons instead
- Write in plain, accessible language that non-technical people can understand
- Each threat must specify which regions it primarily affects and which audience it targets
- Include the authoritative source reporting this threat (FBI, FTC, CISA, Europol, INTERPOL, national CERTs, etc.)
- Focus on threats relevant to seniors, families, and children

Available regions:
${regionList}

Available audiences:
${audienceList}
${existingList}

Respond with a JSON array of threat objects. Each object must have:
- title: Clear, specific title (no em dashes)
- summary: 2-3 sentence description in plain language with actionable advice (no em dashes, use commas and periods)
- source: The authoritative organization reporting this (e.g. "FBI", "FTC", "CISA", "Europol")
- category: One of: scam, phishing, malware, fraud, data_breach, vulnerability, identity_theft
- severity: One of: low, medium, high, critical
- regions: Array of region codes this threat primarily affects (use GLOBAL if it affects everyone)
- audience: One of: seniors, families, children, general
- linkUrl: Optional URL to the source report (only include if you are confident of the URL)

Respond ONLY with the JSON array, no other text.`;

  const response = await anthropic.messages.create({
    model: "claude-haiku-4-5",
    max_tokens: 8192,
    messages: [{ role: "user", content: prompt }],
  });

  const content = response.content[0];
  if (content.type !== "text") {
    throw new Error("Unexpected response type from Claude");
  }

  let parsed: GeneratedThreat[];
  try {
    const jsonText = content.text.trim().replace(/^```json?\n?/, "").replace(/\n?```$/, "");
    parsed = JSON.parse(jsonText);
  } catch (error) {
    console.error("Failed to parse AI response:", content.text);
    throw new Error("Failed to parse threat data from AI");
  }

  const validCategories = ["scam", "phishing", "malware", "fraud", "data_breach", "vulnerability", "identity_theft"];
  const validSeverities = ["low", "medium", "high", "critical"];
  const validAudiences = ["seniors", "families", "children", "general"];
  const validRegions = Object.keys(REGION_DEFINITIONS);

  return parsed
    .filter(t =>
      t.title && t.summary && t.source &&
      validCategories.includes(t.category) &&
      validSeverities.includes(t.severity) &&
      validAudiences.includes(t.audience) &&
      Array.isArray(t.regions) && t.regions.every(r => validRegions.includes(r))
    )
    .map(t => ({
      ...t,
      title: t.title.replace(/\u2014/g, ",").replace(/\u2013/g, ","),
      summary: t.summary.replace(/\u2014/g, ",").replace(/\u2013/g, ","),
    }));
}

export function startThreatRefreshScheduler() {
  console.log("Trending threat refresh scheduler started (every 6 hours)");
  refreshTrendingThreats().catch(err =>
    console.error("Initial threat refresh failed:", err)
  );

  setInterval(() => {
    refreshTrendingThreats().catch(err =>
      console.error("Scheduled threat refresh failed:", err)
    );
  }, 6 * 60 * 60 * 1000);
}

export { REGION_DEFINITIONS, AUDIENCE_DEFINITIONS };
